COMMENT ON VIEW  app_user_public IS 'app_user without password_hash. Use this in the SQL console.';
COMMENT ON TABLE department IS 'Academic departments.';
COMMENT ON TABLE programme IS 'Degree programmes (BCA, MCA ...) belonging to a department.';
COMMENT ON TABLE student IS 'Student profile; user_id points to app_user.';
COMMENT ON TABLE faculty IS 'Faculty profile; user_id points to app_user.';
COMMENT ON TABLE course IS 'Catalogue of courses with credit values.';
COMMENT ON TABLE course_prereq IS 'course_id requires prereq_id to be passed first.';
COMMENT ON TABLE term IS 'Academic term with a lifecycle: REGISTRATION_OPEN, IN_PROGRESS, GRADING, RESULTS_PUBLISHED, CLOSED.';
COMMENT ON TABLE section IS 'A course offered in a term by one faculty, with capacity and a weekly time slot (day_of_week 1=Mon, minutes from midnight).';
COMMENT ON COLUMN section.enrolled_count IS 'Updated only by one atomic conditional UPDATE (seat guard); equals live enrolments.';
COMMENT ON TABLE assessment_component IS 'Parts of the final mark for a section (quiz, midterm, final); weights add up to 100.';
COMMENT ON TABLE enrolment IS 'A student registered in a section. DROPPED rows are kept for history.';
COMMENT ON TABLE class_session IS 'One class meeting of a section on a date.';
COMMENT ON TABLE attendance IS 'Present/absent for each enrolment in a class session.';
COMMENT ON TABLE mark_sheet IS 'Marks lifecycle of a section: DRAFT, SUBMITTED, APPROVED, PUBLISHED.';
COMMENT ON TABLE mark IS 'Marks awarded per component per enrolment.';
COMMENT ON TABLE grade_scale IS '10-point grade scale: highest min_total not above the total wins.';
COMMENT ON TABLE result IS 'Final total, letter grade and grade points per enrolment (written when a term publishes).';
COMMENT ON TABLE term_result IS 'SGPA per student per term (credit-weighted).';
COMMENT ON TABLE notice IS 'Announcements for everyone, students only, or faculty only.';
COMMENT ON TABLE activity_log IS 'Audit trail of logins, writes and denied actions. Streamed live to the Dev area.';
