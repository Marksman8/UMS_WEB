-- UMS web schema. Owned by Flyway; Hibernate/JPA is not used.
-- Naming: pk_ / fk_ / uq_ / ck_ / idx_ prefixes on every constraint and index.

CREATE TABLE app_user (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    username        varchar(40)  NOT NULL,
    password_hash   varchar(100) NOT NULL,
    role            varchar(10)  NOT NULL,
    full_name       varchar(120) NOT NULL,
    email           varchar(160),
    active          boolean      NOT NULL DEFAULT true,
    failed_attempts integer      NOT NULL DEFAULT 0,
    locked_until    timestamptz,
    created_at      timestamptz  NOT NULL DEFAULT now(),
    version         bigint       NOT NULL DEFAULT 0,
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT ck_app_user_role CHECK (role IN ('STUDENT', 'FACULTY', 'ADMIN', 'DEV'))
);
CREATE UNIQUE INDEX uq_app_user_username ON app_user (lower(username));

-- Safe projection for people (and the SQL console) that must never see password hashes.
CREATE VIEW app_user_public AS
    SELECT id, username, role, full_name, email, active, created_at FROM app_user;

CREATE TABLE department (
    id   bigint GENERATED BY DEFAULT AS IDENTITY,
    code varchar(10)  NOT NULL,
    name varchar(120) NOT NULL,
    CONSTRAINT pk_department PRIMARY KEY (id),
    CONSTRAINT uq_department_code UNIQUE (code),
    CONSTRAINT uq_department_name UNIQUE (name)
);

CREATE TABLE programme (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    dept_id     bigint       NOT NULL,
    code        varchar(10)  NOT NULL,
    name        varchar(120) NOT NULL,
    semesters   smallint     NOT NULL,
    CONSTRAINT pk_programme PRIMARY KEY (id),
    CONSTRAINT fk_programme_dept FOREIGN KEY (dept_id) REFERENCES department (id),
    CONSTRAINT uq_programme_code UNIQUE (code),
    CONSTRAINT ck_programme_semesters CHECK (semesters BETWEEN 1 AND 12)
);

CREATE TABLE student (
    user_id          bigint      NOT NULL,
    roll_no          varchar(20) NOT NULL,
    programme_id     bigint      NOT NULL,
    admission_year   smallint    NOT NULL,
    current_semester smallint    NOT NULL DEFAULT 1,
    CONSTRAINT pk_student PRIMARY KEY (user_id),
    CONSTRAINT fk_student_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_student_programme FOREIGN KEY (programme_id) REFERENCES programme (id),
    CONSTRAINT uq_student_roll UNIQUE (roll_no),
    CONSTRAINT ck_student_semester CHECK (current_semester BETWEEN 1 AND 12)
);

CREATE TABLE faculty (
    user_id     bigint      NOT NULL,
    dept_id     bigint      NOT NULL,
    designation varchar(60) NOT NULL DEFAULT 'Assistant Professor',
    CONSTRAINT pk_faculty PRIMARY KEY (user_id),
    CONSTRAINT fk_faculty_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT fk_faculty_dept FOREIGN KEY (dept_id) REFERENCES department (id)
);

CREATE TABLE course (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    code        varchar(12)  NOT NULL,
    title       varchar(160) NOT NULL,
    credits     smallint     NOT NULL,
    dept_id     bigint       NOT NULL,
    description varchar(400),
    CONSTRAINT pk_course PRIMARY KEY (id),
    CONSTRAINT fk_course_dept FOREIGN KEY (dept_id) REFERENCES department (id),
    CONSTRAINT uq_course_code UNIQUE (code),
    CONSTRAINT ck_course_credits CHECK (credits BETWEEN 1 AND 6)
);

CREATE TABLE course_prereq (
    course_id bigint NOT NULL,
    prereq_id bigint NOT NULL,
    CONSTRAINT pk_course_prereq PRIMARY KEY (course_id, prereq_id),
    CONSTRAINT fk_prereq_course FOREIGN KEY (course_id) REFERENCES course (id),
    CONSTRAINT fk_prereq_required FOREIGN KEY (prereq_id) REFERENCES course (id),
    CONSTRAINT ck_prereq_distinct CHECK (course_id <> prereq_id)
);

CREATE TABLE term (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    name      varchar(40) NOT NULL,
    state     varchar(20) NOT NULL DEFAULT 'REGISTRATION_OPEN',
    starts_on date        NOT NULL,
    ends_on   date        NOT NULL,
    version   bigint      NOT NULL DEFAULT 0,
    CONSTRAINT pk_term PRIMARY KEY (id),
    CONSTRAINT uq_term_name UNIQUE (name),
    CONSTRAINT ck_term_state CHECK (state IN ('REGISTRATION_OPEN', 'IN_PROGRESS', 'GRADING', 'RESULTS_PUBLISHED', 'CLOSED')),
    CONSTRAINT ck_term_dates CHECK (ends_on > starts_on)
);

CREATE TABLE section (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    course_id      bigint      NOT NULL,
    term_id        bigint      NOT NULL,
    faculty_id     bigint      NOT NULL,
    code           varchar(10) NOT NULL DEFAULT 'A',
    capacity       integer     NOT NULL,
    enrolled_count integer     NOT NULL DEFAULT 0,
    day_of_week    smallint    NOT NULL,
    start_min      smallint    NOT NULL,
    end_min        smallint    NOT NULL,
    room           varchar(30) NOT NULL DEFAULT 'TBA',
    version        bigint      NOT NULL DEFAULT 0,
    CONSTRAINT pk_section PRIMARY KEY (id),
    CONSTRAINT fk_section_course FOREIGN KEY (course_id) REFERENCES course (id),
    CONSTRAINT fk_section_term FOREIGN KEY (term_id) REFERENCES term (id),
    CONSTRAINT fk_section_faculty FOREIGN KEY (faculty_id) REFERENCES faculty (user_id),
    CONSTRAINT uq_section_identity UNIQUE (term_id, course_id, code),
    CONSTRAINT ck_section_capacity CHECK (enrolled_count >= 0 AND enrolled_count <= capacity AND capacity > 0),
    CONSTRAINT ck_section_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_section_time CHECK (start_min >= 0 AND end_min <= 1440 AND end_min > start_min)
);
CREATE INDEX idx_section_term ON section (term_id, id);
CREATE INDEX idx_section_faculty ON section (faculty_id, term_id);

CREATE TABLE assessment_component (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    section_id bigint       NOT NULL,
    name       varchar(60)  NOT NULL,
    max_marks  numeric(6,2) NOT NULL,
    weight     numeric(5,2) NOT NULL,
    CONSTRAINT pk_component PRIMARY KEY (id),
    CONSTRAINT fk_component_section FOREIGN KEY (section_id) REFERENCES section (id) ON DELETE CASCADE,
    CONSTRAINT uq_component_name UNIQUE (section_id, name),
    CONSTRAINT ck_component_max CHECK (max_marks > 0),
    CONSTRAINT ck_component_weight CHECK (weight > 0 AND weight <= 100)
);

CREATE TABLE enrolment (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    student_id bigint      NOT NULL,
    section_id bigint      NOT NULL,
    state      varchar(10) NOT NULL DEFAULT 'ENROLLED',
    created_at timestamptz NOT NULL DEFAULT now(),
    version    bigint      NOT NULL DEFAULT 0,
    CONSTRAINT pk_enrolment PRIMARY KEY (id),
    CONSTRAINT fk_enrolment_student FOREIGN KEY (student_id) REFERENCES student (user_id),
    CONSTRAINT fk_enrolment_section FOREIGN KEY (section_id) REFERENCES section (id),
    CONSTRAINT ck_enrolment_state CHECK (state IN ('ENROLLED', 'DROPPED'))
);
CREATE UNIQUE INDEX uq_enrolment_live ON enrolment (student_id, section_id) WHERE state = 'ENROLLED';
CREATE INDEX idx_enrolment_section ON enrolment (section_id) WHERE state = 'ENROLLED';
CREATE INDEX idx_enrolment_student ON enrolment (student_id, id);

CREATE TABLE class_session (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    section_id bigint      NOT NULL,
    held_on    date        NOT NULL,
    topic      varchar(160),
    CONSTRAINT pk_class_session PRIMARY KEY (id),
    CONSTRAINT fk_session_section FOREIGN KEY (section_id) REFERENCES section (id) ON DELETE CASCADE,
    CONSTRAINT uq_session_day UNIQUE (section_id, held_on)
);

CREATE TABLE attendance (
    session_id   bigint  NOT NULL,
    enrolment_id bigint  NOT NULL,
    present      boolean NOT NULL,
    CONSTRAINT pk_attendance PRIMARY KEY (session_id, enrolment_id),
    CONSTRAINT fk_attendance_session FOREIGN KEY (session_id) REFERENCES class_session (id) ON DELETE CASCADE,
    CONSTRAINT fk_attendance_enrolment FOREIGN KEY (enrolment_id) REFERENCES enrolment (id)
);
CREATE INDEX idx_attendance_enrolment ON attendance (enrolment_id);

CREATE TABLE mark_sheet (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    section_id   bigint      NOT NULL,
    state        varchar(12) NOT NULL DEFAULT 'DRAFT',
    submitted_at timestamptz,
    decided_at   timestamptz,
    version      bigint      NOT NULL DEFAULT 0,
    CONSTRAINT pk_mark_sheet PRIMARY KEY (id),
    CONSTRAINT fk_sheet_section FOREIGN KEY (section_id) REFERENCES section (id) ON DELETE CASCADE,
    CONSTRAINT uq_sheet_section UNIQUE (section_id),
    CONSTRAINT ck_sheet_state CHECK (state IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'PUBLISHED'))
);

CREATE TABLE mark (
    component_id bigint       NOT NULL,
    enrolment_id bigint       NOT NULL,
    value        numeric(6,2) NOT NULL,
    CONSTRAINT pk_mark PRIMARY KEY (component_id, enrolment_id),
    CONSTRAINT fk_mark_component FOREIGN KEY (component_id) REFERENCES assessment_component (id) ON DELETE CASCADE,
    CONSTRAINT fk_mark_enrolment FOREIGN KEY (enrolment_id) REFERENCES enrolment (id),
    CONSTRAINT ck_mark_nonneg CHECK (value >= 0)
);
CREATE INDEX idx_mark_enrolment ON mark (enrolment_id);

CREATE TABLE grade_scale (
    grade     varchar(2)   NOT NULL,
    min_total numeric(5,2) NOT NULL,
    points    smallint     NOT NULL,
    CONSTRAINT pk_grade_scale PRIMARY KEY (grade),
    CONSTRAINT uq_grade_min UNIQUE (min_total)
);

CREATE TABLE result (
    enrolment_id bigint       NOT NULL,
    total        numeric(5,2) NOT NULL,
    grade        varchar(2)   NOT NULL,
    points       smallint     NOT NULL,
    published_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_result PRIMARY KEY (enrolment_id),
    CONSTRAINT fk_result_enrolment FOREIGN KEY (enrolment_id) REFERENCES enrolment (id),
    CONSTRAINT fk_result_grade FOREIGN KEY (grade) REFERENCES grade_scale (grade)
);

CREATE TABLE term_result (
    student_id bigint       NOT NULL,
    term_id    bigint       NOT NULL,
    credits    integer      NOT NULL,
    sgpa       numeric(4,2) NOT NULL,
    CONSTRAINT pk_term_result PRIMARY KEY (student_id, term_id),
    CONSTRAINT fk_term_result_student FOREIGN KEY (student_id) REFERENCES student (user_id),
    CONSTRAINT fk_term_result_term FOREIGN KEY (term_id) REFERENCES term (id)
);

CREATE TABLE notice (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    title      varchar(160) NOT NULL,
    body       varchar(2000) NOT NULL,
    audience   varchar(10)  NOT NULL DEFAULT 'ALL',
    author_id  bigint       NOT NULL,
    created_at timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT pk_notice PRIMARY KEY (id),
    CONSTRAINT fk_notice_author FOREIGN KEY (author_id) REFERENCES app_user (id),
    CONSTRAINT ck_notice_audience CHECK (audience IN ('ALL', 'STUDENT', 'FACULTY'))
);
CREATE INDEX idx_notice_created ON notice (created_at DESC, id DESC);

CREATE TABLE activity_log (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    at        timestamptz  NOT NULL DEFAULT now(),
    actor     varchar(40)  NOT NULL,
    role      varchar(10),
    action    varchar(40)  NOT NULL,
    entity    varchar(40),
    entity_id varchar(40),
    detail    varchar(300),
    ok        boolean      NOT NULL DEFAULT true,
    CONSTRAINT pk_activity_log PRIMARY KEY (id)
);

