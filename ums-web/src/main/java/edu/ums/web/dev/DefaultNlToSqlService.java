package edu.ums.web.dev;

import edu.ums.web.ai.AiAssistant;
import edu.ums.web.audit.AuditService;
import edu.ums.web.common.ErrorCode;
import edu.ums.web.common.UmsException;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

// Complexity: time O(S) per question to build the schema prompt (S = columns, ~150) plus one bounded model call; space O(S).

/**
 * An AI model (Claude or local Ollama) writes the SQL from the live schema; the result is always passed through the same
 * {@link ConsoleGuard} as hand-typed SQL, so a model mistake or prompt trick cannot widen what the console may do.
 */
@Service
public class DefaultNlToSqlService implements NlToSqlService {

    private static final Logger log = LoggerFactory.getLogger(DefaultNlToSqlService.class);

    private final AiAssistant claude;
    private final DevAiContext context;
    private final ConsoleGuard guard;
    private final LocalSqlSuggester templates;
    private final AuditService audit;
    private final ConsoleService console;

    public DefaultNlToSqlService(AiAssistant claude, DevAiContext context, ConsoleGuard guard,
                                 LocalSqlSuggester templates, AuditService audit, ConsoleService console) {
        this.console = console;
        this.claude = claude;
        this.context = context;
        this.guard = guard;
        this.templates = templates;
        this.audit = audit;
    }

    @Override
    public Suggestion suggest(String question) {
        String note = null;
        if (claude.available()) {
            try {
                String provider = claude.name();
                String sql = draftChecked(question);
                audit.record("AI_SQL", "console", null, provider);
                return new Suggestion(sql, "Generated by the AI model from the live schema and checked with EXPLAIN. Read it before you run it.", provider, null);
            } catch (UmsException e) {
                log.info("AI SQL suggestion not used: {}", e.getMessage());
                note = "The AI answer was not usable (" + e.getMessage() + "), so a built-in template was used instead.";
            }
        }
        Suggestion fromTemplate = templates.suggest(question).orElseThrow(() -> new UmsException(ErrorCode.NOT_FOUND,
                "I could not turn that into a query. Try words like attendance, CGPA, seats, mark sheets, users, courses or activity."));
        audit.record("AI_SQL", "console", null, "templates");
        return new Suggestion(fromTemplate.sql(), fromTemplate.explanation(), "templates", note);
    }

    /**
     * Asks the model for SQL, then proves it with EXPLAIN (plans the query without running it). On a planning error
     * the error text goes back to the model once; a second failure is thrown so the caller can fall back to templates.
     */
    private String draftChecked(String question) {
        List<AiAssistant.Turn> turns = new java.util.ArrayList<>(List.of(new AiAssistant.Turn("user", question)));
        UmsException last = null;
        for (int attempt = 0; attempt < 2; attempt++) {
            String raw = claude.complete(prompt(), turns);
            String sql = guard.check(extractSql(raw));
            try {
                console.run("EXPLAIN " + sql);
                return sql;
            } catch (UmsException e) {
                last = e;
                turns = new java.util.ArrayList<>(List.of(
                        new AiAssistant.Turn("user", question),
                        new AiAssistant.Turn("assistant", sql),
                        new AiAssistant.Turn("user", "That query failed: " + e.getMessage()
                                + ". Use ONLY the tables and columns listed in the schema, exactly as spelled. Reply with the corrected SQL only.")));
            }
        }
        throw last;
    }

    private String prompt() {
        return "You write PostgreSQL for a university database. Reply with ONE read-only SELECT (or WITH ... SELECT) statement "
                + "and nothing else - no explanation, no markdown fences. Never reference app_user or password_hash; use app_user_public. "
                + "Use ONLY the tables and columns listed below, spelled exactly; never invent a column or assume an id column exists. Always add LIMIT 200 or less. Tables (columns) and approximate row counts:\n" + context.schemaText();
    }

    /** Models sometimes wrap SQL in ``` fences; strip them. */
    static String extractSql(String raw) {
        String s = raw.trim();
        if (s.startsWith("```")) {
            int firstNewline = s.indexOf('\n');
            int lastFence = s.lastIndexOf("```");
            if (firstNewline > 0 && lastFence > firstNewline) {
                s = s.substring(firstNewline + 1, lastFence).trim();
            }
        }
        return s;
    }
}
